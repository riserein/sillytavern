import { writeFile, rename, unlink } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createPlatformService } from '../platforms/service.js';
import { buildBuiltinCatalog } from '../platforms/builtin-maintenance.js';
import { BUILTIN_CATALOG } from '../builtin-tracks.js';
const args = process.argv.slice(2),
    sources = [];
let title = BUILTIN_CATALOG.title,
    out = fileURLToPath(new URL('../builtin-tracks.js', import.meta.url));
try {
    for (let i = 0; i < args.length; i++) {
        if (args[i] === '--source' && args[i + 1]) sources.push(args[++i]);
        else if (args[i] === '--name' && args[i + 1]) title = args[++i];
        else if (args[i] === '--out' && args[i + 1]) out = resolve(args[++i]);
        else
            throw new Error(
                '用法：node scripts/update-builtin.mjs --source "歌曲或歌单链接" [--source "另一链接"] [--name "默认曲库"] [--out 文件路径]',
            );
    }
    const catalog = await buildBuiltinCatalog(createPlatformService(), sources, { title, previous: BUILTIN_CATALOG });
    const temp = `${out}.tmp-${process.pid}`;
    let created = false;
    try {
        await writeFile(
            temp,
            `// Generated by scripts/update-builtin.mjs. Metadata only; no audio or account credentials.\nexport const BUILTIN_CATALOG = ${JSON.stringify(catalog, null, 4)};\n`,
            { flag: 'wx' },
        );
        created = true;
        await rename(temp, out);
    } catch (error) {
        if (created) await unlink(temp).catch(() => {});
        throw error;
    }
    console.log(
        `已生成版本 ${catalog.version}：${catalog.tracks.length} 首歌曲信息。请检查来源、许可及播放能力后提交版本。`,
    );
} catch (error) {
    console.error(error.message);
    process.exitCode = 1;
}
