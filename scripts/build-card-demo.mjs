// Build the portable runtime and the original lifecycle regression fixture.
import { readFile, writeFile, mkdir, mkdtemp, rm, rename } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'),
    folder = join(root, 'card-player');
const temporary = await mkdtemp(join(folder, '.build-'));
try {
    const tracks = [];
    for (const [letter, title] of [
        ['a', '测试曲一 · 低音'],
        ['b', '测试曲二 · 中音'],
        ['c', '测试曲三 · 高音'],
    ]) {
        const bytes = await readFile(join(folder, 'demo-assets', `test-tone-${letter}.mp3`));
        tracks.push({
            id: `test-${letter}`,
            title,
            src: `data:audio/mpeg;base64,${bytes.toString('base64')}`,
            sha256: createHash('sha256').update(bytes).digest('hex'),
        });
    }
    const demo = { id: 'riserein-lifecycle-demo-v1', title: '角色播放器 · 生命周期测试', demo: true, tracks };
    await writeFile(join(temporary, 'demo.js'), `export const DEMO=${JSON.stringify(demo)};`);
    const result = spawnSync(
        'npm',
        [
            'exec',
            '--yes',
            '--package',
            'esbuild@0.25.10',
            '--',
            'esbuild',
            join(folder, 'entry.js'),
            '--bundle',
            '--format=iife',
            '--target=es2022',
            '--tree-shaking=true',
            '--minify',
            '--legal-comments=none',
            '--global-name=RisereinCardPlayer',
            `--outfile=${join(temporary, 'demo.js.out')}`,
        ],
        {
            encoding: 'utf8',
            cwd: root,
            env: {
                ...process.env,
                npm_config_cache: process.env.npm_config_cache || join(tmpdir(), 'stm-ui-build-cache'),
            },
        },
    );
    if (result.status !== 0) throw new Error(result.stderr || '角色播放器打包失败。');
    const runtime =
        '/*\n' +
        (await readFile(join(root, 'LICENSE'), 'utf8')) +
        '*/\n' +
        (await readFile(join(temporary, 'demo.js.out'), 'utf8'));
    const content =
        '/* Riserein card-player lifecycle demo. MIT. Original synthetic test tones included. */\n(()=>{' +
        runtime +
        '\nRisereinCardPlayer.startCharacterPlayer(' +
        JSON.stringify(demo) +
        ');})();';
    if (/\bindexedDB\b|stm-player|riserein_music_player|\.\/assets\/|import\(/.test(content))
        throw new Error('构建意外包含完整版或外部运行依赖，拒绝覆盖已生成文件。');
    const script = {
        type: 'script',
        enabled: false,
        name: '角色播放器 · 三曲生命周期测试',
        id: '08396994-ffeb-4b0d-b4da-90b8e9a75baa',
        content,
        info: 'Riserein 独立阶段一测试。仅含本项目生成的三段合成音。导入到角色脚本并手动启用；不依赖完整版音乐插件。',
        button: { enabled: false, buttons: [] },
        data: {},
        export_with: { data: true, button: true },
    };
    const inventory = {
        projectId: demo.id,
        purpose: 'lifecycle-test-only',
        license: 'MIT; generated by this project, no reference-card resources',
        tracks: tracks.map(({ src, ...track }) => ({
            ...track,
            durationSeconds: 120,
            resource: 'embedded audio/mpeg data URI',
        })),
    };
    for (const [name, text] of [
        ['runtime.js', runtime],
        ['demo.js', content],
        ['demo.tavern-helper.json', JSON.stringify(script, null, 2) + '\n'],
        ['songs.json', JSON.stringify(inventory, null, 2) + '\n'],
    ])
        await writeFile(join(temporary, name + '.ready'), text);
    await mkdir(join(folder, 'dist'), { recursive: true });
    for (const name of ['runtime.js', 'demo.js', 'demo.tavern-helper.json', 'songs.json'])
        await rename(join(temporary, name + '.ready'), join(folder, 'dist', name));
    console.log(
        'Built independent lifecycle fixture: 3 embedded original test tones, no full-plugin runtime or storage dependency.',
    );
} finally {
    await rm(temporary, { recursive: true, force: true });
}
